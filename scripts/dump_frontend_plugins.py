"""Dump the backend-declared frontend plugin list as TypeScript, offline.

Instantiating the plugin loader registers every plugin's hooks with no DB,
server, or event loop. The output is the generated frontend module listing the
plugins that declare a frontend page (the ``FRONTEND_APPS`` hook) and the icon
names each plugin declares for its display info and sidebar entry, sorted so
the file is diff-stable.

With no arguments the module is written to stdout, which is how it is inspected
by hand. Pass ``-o/--output <path>`` to write a file instead; the write is
atomic (temp file in the target's directory, then replaced), so a failed dump
leaves the previous file intact rather than truncating it the way ``> file``
redirection does.

The generated module is committed as ``frontend/lib/plugins/generated.ts``
(regenerate with ``make frontend.build.plugins``); tests on both tiers fail
when the committed file drifts from the declarations.
"""

import argparse
import logging
import os
import sys
import tempfile
from pathlib import Path

# Redirect all log output to stderr before importing app modules so that the
# only thing written to stdout is the generated TypeScript (see
# scripts/dump_openapi.py for the rationale).
logging.basicConfig(stream=sys.stderr)

from sparkth.lib.frontend import (  # noqa: E402
    get_plugin_display_info,
    get_plugin_sidebar_entry,
    plugin_has_frontend,
)
from sparkth.lib.plugins import get_plugin_loader  # noqa: E402

HEADER = """\
// Generated by scripts/dump_frontend_plugins.py. Do not edit.
// Backend plugins that declare a frontend page (FRONTEND_APPS hook), and the icon names
// each plugin declares (DISPLAY_INFO and SIDEBAR_ENTRIES hooks).
// Regenerate with `make frontend.build.plugins`; tests fail on drift.
"""


def _declared_icons(plugin_name: str) -> list[str]:
    """The icon names a plugin declared for its display info and sidebar entry, sorted, each once."""
    declarations = (get_plugin_display_info(plugin_name), get_plugin_sidebar_entry(plugin_name))
    return sorted({declared.icon for declared in declarations if declared is not None and declared.icon})


def _render_icon_names(plugin_names: list[str]) -> str:
    """The ``PLUGIN_ICON_NAMES`` constant: each plugin that declared an icon, with its icon names."""
    entries = []
    for name in plugin_names:
        icons = _declared_icons(name)
        if icons:
            quoted = ", ".join(f'"{icon}"' for icon in icons)
            entries.append(f'  "{name}": [{quoted}],\n')
    return "export const PLUGIN_ICON_NAMES = {\n" + "".join(entries) + "} as const;\n"


def render() -> str:
    """Render the generated TypeScript module for the declared frontend plugins and icons."""
    loader = get_plugin_loader()
    plugin_names = sorted(name for name, _ in loader.get_loaded_plugins())
    quoted = ", ".join(f'"{name}"' for name in plugin_names if plugin_has_frontend(name))
    return (
        f"{HEADER}\n"
        f"export const FRONTEND_PLUGIN_NAMES = [{quoted}] as const;\n"
        "\n"
        "export type FrontendPluginName = (typeof FRONTEND_PLUGIN_NAMES)[number];\n"
        "\n"
        f"{_render_icon_names(plugin_names)}"
    )


def _write_atomically(path: Path, contents: str) -> None:
    """Replace ``path`` with ``contents`` only once the full dump is in hand."""
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=path.parent, prefix=f".{path.name}.", delete=False
    ) as tmp:
        tmp.write(contents)
        tmp_path = Path(tmp.name)
    os.replace(tmp_path, path)


def main(argv: list[str] | None = None) -> None:
    """Write the generated module to ``--output``, or to stdout when it is omitted."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        help="file to write the generated module to (default: stdout)",
    )
    args = parser.parse_args(argv)

    contents = render()
    if args.output is None:
        sys.stdout.write(contents)
    else:
        _write_atomically(args.output, contents)


if __name__ == "__main__":
    main()
